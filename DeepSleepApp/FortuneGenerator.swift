    // MARK: - Main Generation Function
    func generateDailyFortune(for date: Date, birthDate: Date? = nil, gender: Int = 0) -> DailyFortune {
        let zodiacSign = getZodiacSign(from: birthDate ?? Date())
        
        // Use date as seed for consistent daily fortune
        let calendar = Calendar.current
        let dayOfYear = calendar.ordinality(of: .day, in: .year, for: date) ?? 1
        let seed = dayOfYear + calendar.component(.year, from: date) + gender
        
        var random = SeededRandom(seed: seed)
        
        let generalFortune = generalFortunes[random.nextInt(in: 0..<generalFortunes.count)]
        let loveFortune = relationshipFortunes[random.nextInt(in: 0..<relationshipFortunes.count)]
        let workFortune = workFortunes[random.nextInt(in: 0..<workFortunes.count)]
        let healthFortune = healthFortunes[random.nextInt(in: 0..<healthFortunes.count)]
        let luckyColor = luckyColors[random.nextInt(in: 0..<luckyColors.count)]
        let luckyNumber = random.nextInt(in: 1...99)
        let luckyItem = luckyItems[random.nextInt(in: 0..<luckyItems.count)]
        let overallScore = random.nextInt(in: 3...5) // Generally positive fortune
        
        return DailyFortune(
            date: date,
            zodiacSign: zodiacSign,
            generalFortune: generalFortune,
            loveFortune: loveFortune,
            workFortune: workFortune,
            healthFortune: healthFortune,
            luckyColor: luckyColor,
            luckyNumber: luckyNumber,
            luckyItem: luckyItem,
            overallScore: overallScore
        )
    }
    
